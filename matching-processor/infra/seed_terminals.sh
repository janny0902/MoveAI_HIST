# Firestore 일괄 커밋. 한 건씩 PATCH하면 120여 번 왕복이라 느리다.
# 한글은 curl 인자가 아니라 stdin으로 넘긴다 - Git Bash가 네이티브 curl.exe에 넘기는
# 인자를 ANSI 코드페이지(CP949)로 변환해 UTF-8이 깨진다.
writes=""
count=0
while IFS=$'\t' read -r code name address lat lng; do
  [[ -z "${code:-}" ]] && continue
  [[ -n "$writes" ]] && writes="${writes},"
  writes="${writes}{\"update\":{\"name\":\"${DOCS}/terminals/${code}\",\"fields\":{
      \"terminal_code\":{\"stringValue\":\"${code}\"},
      \"name\":{\"stringValue\":\"${name}(가상)\"},
      \"address\":{\"stringValue\":\"${address}\"},
      \"lat\":{\"doubleValue\":${lat}},
      \"lng\":{\"doubleValue\":${lng}}}},
      \"updateMask\":{\"fieldPaths\":[\"terminal_code\",\"name\",\"address\",\"lat\",\"lng\"]}}"
  count=$((count + 1))
done <<< "$TERMINALS"

printf '{"writes":[%s]}' "$writes" | curl -s -X POST \
  "https://firestore.googleapis.com/v1/${DOCS}:commit" \
  -H "Authorization: Bearer ${TOKEN}" \
  -H "Content-Type: application/json" \
  -d @- > /dev/null

echo "작업터미널 ${count}곳 등록 (가상 좌표)"
echo
echo "확인:  curl -s \"\${MATCHING_URL}/v1/terminals\""
echo "대응표는 인스턴스마다 TERMINAL_CACHE_TTL_S(300초) 캐시된다 - 즉시 반영되지 않을 수 있다."
